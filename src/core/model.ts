/**
 * Предметная модель CrossW. Единственный контракт между слоями.
 *
 * Слой `core` не знает про React, DOM, Next и файловую систему. Всё, что здесь
 * лежит — типы и чистые функции над ними.
 */

/** Язык кроссворда. Английские кроссворды в первую версию не входят, но поле есть с первого дня. */
export type Lang = 'ru' | 'en'

export type Difficulty = 'easy' | 'medium' | 'hard'

/** Направление слова: горизонталь и вертикаль. */
export type Dir = 'H' | 'V'

/**
 * Откуда взялось слово. Нужно валидатору для метрики тематичности.
 * - `topic`  — уникальное слово темы (ВОЛАНД, ЕРШАЛАИМ)
 * - `dict`   — обычное слово с тематическим определением (МАСЛО → «Что разлила Аннушка»)
 * - `filler` — обычное слово со словарным определением (ОКНО → «Проём в стене»)
 */
export type Origin = 'topic' | 'dict' | 'filler'

/** Символ блока в сетке. Всё остальное — буквенная клетка. */
export const BLOCK = '#'

/**
 * Ключ слова в source-формате: номер плюс направление, «12A» или «3D».
 * A — across (по горизонтали), D — down (по вертикали). Латиница намеренно:
 * ключи не показываются пользователю и должны быть безопасны в JSON и URL.
 */
export type EntryKey = `${number}A` | `${number}D`

