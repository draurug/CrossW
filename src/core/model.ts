/**
 * Одно слово в скомпилированном кроссворде.
 *
 * `cells` — плоские индексы клеток по порядку чтения, `cells[k]` это k-я буква
 * ответа. Благодаря этому движку не нужно знать ни про геометрию, ни про
 * направление: он работает с позицией внутри слова.
 */
export interface CompiledEntry {
  /**
   * Номер для показа: тот же, что стоит в клетке-начале и в списке определений.
   *
   * Идентификатором слова он НЕ является. Сквозная нумерация даёт клетке один
   * номер на оба направления, поэтому у горизонтального и вертикального слова
   * из одной клетки номер общий: в сетке 9×9 из фикстуры №1 — это и ШАР, и ШОУ.
   * Слово однозначно задаётся своими клетками; движок нумерует слова сам
   * (`IndexEntry.id`), чтобы курсор ссылался на конкретное слово.
   */
  number: number
  dir: Dir
  /** Плоские индексы клеток: `row * cols + col`. */
  cells: number[]
  clue: string
  /** Категория ответа. Показывается по просьбе игрока, а не сразу. */
  category?: string
  /** Цитата из книги с отточием вместо ответа. Тоже по просьбе игрока. */
  quote?: string
}

/** Кроссворд в виде, готовом для плеера: `public/p/<id>.json`. */
export interface CompiledPuzzle {
  meta: {
    id: string
    lang: Lang
    topicId: string
    title: string
    difficulty: Difficulty
    rows: number
    cols: number
  }
  /**
   * Плоский массив клеток длиной `rows * cols`:
   * `-1` — блок, `0` — буквенная клетка без номера, `> 0` — номер клетки.
   */
  cells: number[]
  entries: CompiledEntry[]
  /** Хэш решения. Входит в ключ localStorage: чужой прогресс не подхватится. */
  solutionHash: string
}

/**
 * Решение отдельным файлом `public/p/<id>.sol`.
 * Строка букв в порядке `letterCells`, зашифрованная XOR по id кроссворда.
 * Это защита от «посмотреть исходник», не криптография.
 */
export type EncodedSolution = string
