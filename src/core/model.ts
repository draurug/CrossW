// ─────────────────────────────────────────────────────────────────────────────

/**
 * Кроссворд в человекочитаемом виде: `content/puzzles/<id>.json`.
 *
 * Сетка хранится с буквами — так её можно прочитать и проверить глазами прямо
 * в git-диффе. Решение вынимается из неё на сборке (см. `tools/build-content.ts`),
 * в браузер открытым текстом не уезжает.
 */
export interface PuzzleSource {
  id: string
  lang: Lang
  topicId: string
  title: string
  difficulty: Difficulty
  /** Строки сетки одинаковой длины: `#` — блок, буква — клетка. */
  grid: string[]
  /** Определения по ключу слова: `{ "1A": "Транспорт, обезглавивший Берлиоза" }`. */
  clues: Record<string, string>
  /** Происхождение каждого слова. Отсутствующие считаются `filler`. */
  origins?: Record<string, Origin>
  /** Категория ответа по ключу слова: «предмет одежды», «персонаж». */
  categories?: Record<string, string>
  /** Цитата из книги по ключу слова — вторая ступень подсказки. */
  quotes?: Record<string, string>
  /** Заметка автора: чем этот кроссворд отличается, что проверить на ревью. */
  note?: string
}

/** Тема: `content/topics.json`. */
export interface Topic {
  id: string
  lang: Lang
  slug: string
  title: string
  /** Одно-два предложения для карточки и SEO. */
  description: string
  /** Что это за источник: книга, фильм, общая лексика. */
  kind: 'book' | 'film' | 'general'
}

/** Одно определение к ответу. */
export interface PackClue {
  text: string
  /** `topic` — факт из книги или фильма, `dict` — обычное словарное значение. */
  kind: 'topic' | 'dict'
  /** Вариант сложности. Отсутствие означает «подходит любому уровню». */
  difficulty?: 'easy' | 'hard'
  /**
   * Категория именно этого значения — перебивает `PackEntry.category`.
   *
   * Нужна словам-омонимам. ЯРД с определением «Скотленд-…, служба Лестрейда»
   * это полиция, а не «единица измерения»: категория от слова тут соврала бы.
   */
  category?: string
  /**
   * Фраза из книги, где это слово встречается, — вторая ступень подсказки.
   *
   * Сам ответ в цитате заменён отточием, иначе подсказка выдала бы слово
   * целиком: «Зашли вёдра в избу и сами стали на …». Привязана к значению,
   * а не к слову: у словарного определения цитаты из книги быть не может.
   */
  quote?: string
}

/** Слово темы с определениями: элемент `content/packs/<id>.json`. */
export interface PackEntry {
  /** Ответ заглавными буквами, Ё сведена к Е. */
  answer: string
  clues: PackClue[]
  /** Видимое происхождение факта: «МиМ, гл. 3». Для тематических определений обязательно. */
  source?: string
  /**
   * Слово для тех, кто читал внимательно: второстепенные имена и мелкие детали
   * вроде МОРСТЕН или ЦЕКУБА. В лёгкие кроссворды такие слова не попадают.
   *
   * Речь не о редкости слова и не о его длине. КЕБ и ГИПС — обычные слова,
   * они остаются в лёгком. А ЖЕМЧУЖИНА обычная, но если она опознаётся только
   * через Мэри Морстен, то определение к ней уже для знатока.
   */
  hard?: boolean
  /**
   * Что это за слово в двух словах: «предмет одежды», «персонаж», «место».
   *
   * Первая ступень подсказки. «В них Иван явился к писателям» — проверка
   * памяти; та же строчка плюс «предмет одежды» — уже задача на догадку.
   *
   * Значение по умолчанию: если у выбранного определения есть своя категория,
   * берётся она (слова-омонимы).
   */
  category?: string
}

/** Тематический пак: `content/packs/<id>.json`. */
export interface Pack {
  id: string
  lang: Lang
  topicId: string
  title: string
  entries: PackEntry[]
}

